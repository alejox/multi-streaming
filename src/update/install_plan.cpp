// The installer gives OBS this long to exit before leaving the package for the next close.
constexpr int kWaitForExitSeconds = 600;

bool has_control_characters(std::string_view text)
{
	return std::any_of(text.begin(), text.end(), [](char c) { return static_cast<unsigned char>(c) < 0x20; });
}

bool is_separator(char c, bool windows)
{
	return c == '/' || (windows && c == '\\');
}

bool is_absolute(std::string_view path, bool windows)
{
	if (!windows) {
		return path.size() > 1 && path.front() == '/';
	}
	const bool drive = path.size() > 3 && ((path[0] >= 'A' && path[0] <= 'Z') || (path[0] >= 'a' && path[0] <= 'z')) &&
			   path[1] == ':' && is_separator(path[2], true);
	const bool unc = path.size() > 2 && path[0] == '\\' && path[1] == '\\';
	return drive || unc;
}

std::string_view last_component(std::string_view path, bool windows)
{
	while (!path.empty() && is_separator(path.back(), windows)) {
		path.remove_suffix(1);
	}
	std::size_t start = path.size();
	while (start > 0 && !is_separator(path[start - 1], windows)) {
		--start;
	}
	return path.substr(start);
}

// Whether `inner` is `outer` or lies inside it, comparing case-insensitively on Windows.
bool is_within(std::string_view inner, std::string_view outer, bool windows)
{
	const auto same = [windows](char a, char b) {
		if (windows) {
			const auto fold = [](char c) {
				if (c == '/') {
					return '\\';
				}
				return c >= 'A' && c <= 'Z' ? static_cast<char>(c - 'A' + 'a') : c;
			};
			return fold(a) == fold(b);
		}
		return a == b;
	};
	while (!outer.empty() && is_separator(outer.back(), windows)) {
		outer.remove_suffix(1);
	}
	if (inner.size() < outer.size() || !std::equal(outer.begin(), outer.end(), inner.begin(), same)) {
		return false;
	}
	return inner.size() == outer.size() || is_separator(inner[outer.size()], windows);
}

bool is_valid(const InstallPlan &plan)
{
	const bool windows = plan.platform == UpdatePlatform::WindowsX64;
	if (plan.obs_pid <= 0 || !parse_semver(plan.version)) {
		return false;
	}
	for (const std::string *path : {&plan.install_root, &plan.archive, &plan.staging_dir, &plan.result_file}) {
		if (!is_absolute(*path, windows) || has_control_characters(*path)) {
			return false;
		}
	}
	if (last_component(plan.install_root, windows) != package_root_name(plan.platform)) {
		return false;
	}
	// The installer deletes the staging folder at the end and replaces the install root.
	return !is_within(plan.staging_dir, plan.install_root, windows) &&
	       !is_within(plan.install_root, plan.staging_dir, windows) &&
	       !is_within(plan.result_file, plan.staging_dir, windows);
}

std::string render_posix(const InstallPlan &plan)
{
	const bool macos = plan.platform == UpdatePlatform::MacosArm64;
	std::string s;
	s += "#!/bin/sh\n";
	s += "# Generated by obs-multi-stream. Installs a staged update once OBS has exited and puts\n";
	s += "# the previous version back if any step fails.\n";
	s += "trap '' HUP INT\n";
	s += "obs_pid=" + std::to_string(plan.obs_pid) + "\n";
	s += "version=" + posix_quote(plan.version) + "\n";
	s += "install_root=" + posix_quote(plan.install_root) + "\n";
	s += "archive=" + posix_quote(plan.archive) + "\n";
	s += "staging=" + posix_quote(plan.staging_dir) + "\n";
	s += "result=" + posix_quote(plan.result_file) + "\n";
	s += "package_root=" + posix_quote(package_root_name(plan.platform)) + "\n";
	s += "backup=\"$install_root.update-backup\"\n";
	s += "extract=\"$staging/extract\"\n";
	s += "\n";
	s += "finish() {\n";
	s += "\tprintf '%s %s %s\\n' \"$1\" \"$version\" \"$2\" > \"$result\"\n";
	s += "\trm -rf \"$staging\"\n";
	s += "\texit 0\n";
	s += "}\n";
	s += "\n";
	s += "waited=0\n";
	s += "while kill -0 \"$obs_pid\" 2>/dev/null; do\n";
	s += "\t# Still running: keep the package for the next close.\n";
	s += "\t[ \"$waited\" -ge " + std::to_string(kWaitForExitSeconds) + " ] && exit 0\n";
	s += "\tsleep 1\n";
	s += "\twaited=$((waited + 1))\n";
	s += "done\n";
	s += "\n";
	s += "rm -rf \"$extract\"\n";
	s += "mkdir -p \"$extract\" || finish failed \"cannot create the extraction folder\"\n";
	if (macos) {
		s += "ditto -x -k \"$archive\" \"$extract\" || finish failed \"cannot extract the package\"\n";
	} else {
		s += "tar -xzf \"$archive\" -C \"$extract\" || finish failed \"cannot extract the package\"\n";
	}
	s += "[ -d \"$extract/$package_root\" ] || finish failed \"unexpected package layout\"\n";
	s += "\n";
	s += "rm -rf \"$backup\"\n";
	s += "if [ -e \"$install_root\" ]; then\n";
	s += "\tmv \"$install_root\" \"$backup\" || finish failed \"cannot move the current version aside\"\n";
	s += "fi\n";
	if (macos) {
		s += "if ditto \"$extract/$package_root\" \"$install_root\"; then\n";
	} else {
		s += "if cp -R \"$extract/$package_root\" \"$install_root\"; then\n";
	}
	s += "\trm -rf \"$backup\"\n";
	s += "\tfinish ok installed\n";
	s += "fi\n";
	s += "rm -rf \"$install_root\"\n";
	s += "if [ -e \"$backup\" ]; then\n";
	s += "\tmv \"$backup\" \"$install_root\"\n";
	s += "fi\n";
	s += "finish failed \"cannot copy the new version; the previous one was restored\"\n";
	return s;
}

std::string render_powershell(const InstallPlan &plan)
{
	std::string s;
	s += "# Generated by obs-multi-stream. Installs a staged update once OBS has exited and puts\n";
	s += "# the previous version back if any step fails.\n";
	s += "$ErrorActionPreference = 'Stop'\n";
	s += "$obsPid = " + std::to_string(plan.obs_pid) + "\n";
	s += "$version = " + powershell_quote(plan.version) + "\n";
	s += "$installRoot = " + powershell_quote(plan.install_root) + "\n";
	s += "$archive = " + powershell_quote(plan.archive) + "\n";
	s += "$staging = " + powershell_quote(plan.staging_dir) + "\n";
	s += "$result = " + powershell_quote(plan.result_file) + "\n";
	s += "$packageRoot = " + powershell_quote(package_root_name(plan.platform)) + "\n";
	s += "$backup = $installRoot + '.update-backup'\n";
	s += "$extract = Join-Path $staging 'extract'\n";
	s += "\n";
	s += "function Finish([string]$outcome, [string]$detail) {\n";
	s += "\ttry { Set-Content -LiteralPath $result -Value \"$outcome $version $detail\" -Encoding UTF8 } catch {}\n";
	s += "\tRemove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue\n";
	s += "\texit 0\n";
	s += "}\n";
	s += "\n";
	s += "$obs = Get-Process -Id $obsPid -ErrorAction SilentlyContinue\n";
	s += "if ($obs -and -not $obs.WaitForExit(" + std::to_string(kWaitForExitSeconds * 1000) + ")) {\n";
	s += "\t# Still running: keep the package for the next close.\n";
	s += "\texit 0\n";
	s += "}\n";
	s += "# Lets Windows release the plugin's file handles.\n";
	s += "Start-Sleep -Seconds 2\n";
	s += "\n";
	s += "try {\n";
	s += "\tif (Test-Path -LiteralPath $extract) { Remove-Item -LiteralPath $extract -Recurse -Force }\n";
	s += "\tExpand-Archive -LiteralPath $archive -DestinationPath $extract -Force\n";
	s += "} catch { Finish 'failed' 'cannot extract the package' }\n";
	s += "$source = Join-Path $extract $packageRoot\n";
	s += "if (-not (Test-Path -LiteralPath $source -PathType Container)) {\n";
	s += "\tFinish 'failed' 'unexpected package layout'\n";
	s += "}\n";
	s += "\n";
	s += "$movedAside = $false\n";
	s += "try {\n";
	s += "\tif (Test-Path -LiteralPath $backup) { Remove-Item -LiteralPath $backup -Recurse -Force }\n";
	s += "\tif (Test-Path -LiteralPath $installRoot) {\n";
	s += "\t\tMove-Item -LiteralPath $installRoot -Destination $backup\n";
	s += "\t\t$movedAside = $true\n";
	s += "\t}\n";
	s += "} catch { Finish 'failed' 'cannot move the current version aside' }\n";
	s += "\n";
	s += "$installed = $false\n";
	s += "try {\n";
	s += "\tCopy-Item -LiteralPath $source -Destination $installRoot -Recurse\n";
	s += "\t$installed = $true\n";
	s += "} catch {}\n";
	s += "if ($installed) {\n";
	s += "\tif ($movedAside) { Remove-Item -LiteralPath $backup -Recurse -Force -ErrorAction SilentlyContinue }\n";
	s += "\tFinish 'ok' 'installed'\n";
	s += "}\n";
	s += "Remove-Item -LiteralPath $installRoot -Recurse -Force -ErrorAction SilentlyContinue\n";
	s += "if ($movedAside) {\n";
	s += "\ttry { Move-Item -LiteralPath $backup -Destination $installRoot } catch {}\n";
	s += "}\n";
	s += "Finish 'failed' 'cannot copy the new version; the previous one was restored'\n";
	return s;
}

std::string_view trim(std::string_view text)
{
	constexpr std::string_view kBom = "\xEF\xBB\xBF";
	if (text.substr(0, kBom.size()) == kBom) {
		text.remove_prefix(kBom.size());
	}
	while (!text.empty() && (text.back() == '\n' || text.back() == '\r' || text.back() == ' ')) {
		text.remove_suffix(1);
	}
	while (!text.empty() && text.front() == ' ') {
		text.remove_prefix(1);
	}
	return text;
}


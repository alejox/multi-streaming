std::string posix_quote(std::string_view text)
{
	std::string out = "'";
	for (const char c : text) {
		if (c == '\'') {
			out += "'\\''";
		} else {
			out += c;
		}
	}
	out += '\'';
	return out;
}

std::string powershell_quote(std::string_view text)
{
	std::string out = "'";
	for (const char c : text) {
		out += c;
		if (c == '\'') {
			out += '\'';
		}
	}
	out += '\'';
	return out;
}

std::string_view install_script_name(UpdatePlatform platform)
{
	return platform == UpdatePlatform::WindowsX64 ? "install.ps1" : "install.sh";
}

std::optional<std::string> render_install_script(const InstallPlan &plan)
{
	if (!is_valid(plan)) {
		return std::nullopt;
	}
	return plan.platform == UpdatePlatform::WindowsX64 ? render_powershell(plan) : render_posix(plan);
}

std::optional<InstallResult> parse_install_result(std::string_view text)
{
	text = trim(text);
	const std::size_t first_space = text.find(' ');
	if (first_space == std::string_view::npos) {
		return std::nullopt;
	}
	const std::string_view outcome = text.substr(0, first_space);
	std::string_view rest = text.substr(first_space + 1);
	const std::size_t second_space = rest.find(' ');
	const std::string_view version = rest.substr(0, second_space);
	if ((outcome != "ok" && outcome != "failed") || !parse_semver(version)) {
		return std::nullopt;
	}
	InstallResult result;
	result.ok = outcome == "ok";
	result.version = std::string(version);
	if (second_space != std::string_view::npos) {
		result.detail = std::string(trim(rest.substr(second_space + 1)));
	}
	return result;
}

